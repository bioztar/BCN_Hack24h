/** Markdown export of a report (GET /api/analyze/:id.md), following both skills' report templates. */
import type { Citation, Report } from "./types.js";

const cites = (cs: Citation[]) => (cs.length ? cs.map((c) => `[${c.display}](${c.url})`).join(", ") : "—");
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n+/g, " ");

export function reportMarkdown(r: Report, publicUrl = "https://warden.pro7ocol.com/analyze/"): string {
  const L: string[] = [];
  const s = r.summary;
  L.push(`# Compliance readiness report — ${r.title}`, "");
  L.push(`- **Date**: ${r.createdAt.slice(0, 10)}`);
  L.push(`- **Artifact type**: ${r.kind === "repo" ? "codebase (public GitHub repository)" : r.kind === "document" ? "design document" : "product idea"}`);
  L.push(`- **Checklists applied**: eu-ai-act \`${r.checklists["eu-ai-act"]}\` · warden \`${r.checklists.warden}\``);
  L.push(`- **EU AI Act**: ${s.aiAct.headline} (confidence ${s.aiAct.confidence.toUpperCase()})`);
  L.push(`- **Overall verdict (warden)**: ${s.wardenVerdict}`);
  L.push(`- **Findings**: ${s.counts.critical} critical · ${s.counts.high} high · ${s.counts.medium} medium · ${s.counts.low} low`);
  if (s.headlinePenalty) L.push(`- **Headline penalty exposure**: ${s.headlinePenalty.framework} — ${s.headlinePenalty.cap} (${cites(s.headlinePenalty.citations)})`);
  L.push("");

  L.push("## 1. EU AI Act — classification rationale", "");
  L.push(`**Risk tier**: ${r.aiAct.tier} · **Roles**: ${r.aiAct.roles.join(", ") || "—"} · **Confidence**: ${r.aiAct.confidence}`, "");
  for (const d of r.aiAct.decisions) L.push(`- **${d.step}** — ${d.verdict}. ${d.reasoning}${d.evidence ? ` _Evidence_: ${d.evidence}` : ""} (${cites(d.citations)})`);
  L.push("");

  L.push("## 2. Applicability (warden)", "", "| Framework | Verdict | Role | Basis | Provisions |", "|---|---|---|---|---|");
  for (const f of r.warden.frameworks) L.push(`| ${f.framework} | ${f.status} | ${cell(f.role)} | ${cell(f.basis)} | ${cites(f.citations)} |`);
  L.push("", `> ${r.handoff}`, "");

  L.push("## 3. Findings (severity-ranked)", "");
  if (!r.findings.length) L.push("No gaps found against the applied checklists.", "");
  for (const f of r.findings) {
    L.push(`### [${f.id}] ${f.title} — ${f.severity.toUpperCase()}${f.status === "unclear" ? " (unclear)" : ""}`, "");
    L.push(`- **What**: ${f.what}`, `- **Why it matters**: ${f.why}`, `- **Provisions**: ${cites(f.citations)}`, `- **Fix**: ${f.fix}`, `- **Effort**: ${f.effort}`, `- **Evidence**: ${f.evidence}`);
    if (f.overlap.length) L.push(`- **Overlap rows**: ${f.overlap.join(", ")}`);
    L.push("");
  }

  if (r.overlap.length) {
    L.push("## 4. Build once, evidence many (overlap matrix)", "", "| # | Control | Frameworks satisfied | Findings |", "|---|---|---|---|");
    for (const o of r.overlap) L.push(`| ${o.id} | ${cell(o.theme)} | ${o.cells.map((c) => `${c.framework}: ${cites(c.citations)}`).join("; ")} | ${o.findings.join(", ") || "—"} |`);
    L.push("");
  }

  if (r.deadlines.length) {
    L.push("## 5. Deadlines & reporting clocks", "", "| When | Framework | What | Source |", "|---|---|---|---|");
    for (const d of r.deadlines) L.push(`| ${cell(d.date)} | ${d.framework} | ${cell(d.event)} | ${cites(d.citations)} |`);
    L.push("");
  }

  if (r.penalties.length) {
    L.push("## 6. Enforcement exposure", "", "| Framework | Cap | Basis | Source |", "|---|---|---|---|");
    for (const p of r.penalties) L.push(`| ${p.framework} | ${cell(p.cap)} | ${cell(p.basis)} | ${cites(p.citations)} |`);
    L.push("");
  }

  L.push("## 7. Checklist", "", "| Skill | Item | Severity | Verdict | Evidence |", "|---|---|---|---|---|");
  for (const c of r.checklist) L.push(`| ${c.skill} | ${c.itemId} ${cell(c.title)} | ${c.severity} | ${c.status} (${c.verdict}) | ${cell(c.evidence)} |`);
  L.push("");

  if (r.assumptions.length || r.warnings.length) {
    L.push("## 8. Assumptions & open questions", "");
    for (const a of [...r.assumptions, ...r.warnings]) L.push(`- ${a}`);
    L.push("");
  }

  if (r.explainer) {
    L.push("## In plain language", "", r.explainer.body, "", `Sources: ${cites(r.explainer.sources)}`, "");
  }

  L.push("---", "", `Generated by warden (by Pro7ocol) — ${publicUrl}`, "", `> ${r.disclaimer}`, "");
  return L.join("\n");
}
