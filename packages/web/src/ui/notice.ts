import type { Notice, Persona } from "../contract";
import { h, fmtEur, safeUrl } from "../dom";
import { POCKET_URL, REPORT_URL, withFlags } from "../env";
import { chime } from "../stage/sfx";
import { qrBox } from "./qr";

function nameOf(officers: Persona[], id: string): Persona {
  return officers.find((p) => p.id === id) ?? { id, name: id, title: "Official", stills: {}, color: "#003399" };
}

export function ombudsman(): HTMLElement {
  const close = h("button", { class: "btn primary", type: "button" }, "OK");
  const dlg = h(
    "div",
    { class: "modal", role: "dialog", "aria-modal": "true" },
    h(
      "div",
      { class: "mail" },
      h("div", { class: "mail-head" }, h("b", null, "Automatic reply: "), "Your appeal (ref. APL-2026-4812)"),
      h("p", { class: "mail-meta" }, "From: European Ombudsman <no-reply@ombudsman.europa.eu.invalid>", h("br"), "To: You", h("br"), "Priority: Low"),
      h(
        "div",
        { class: "mail-body" },
        h("p", null, "Thank you for your message."),
        h("p", null, "I am currently out of the office until the entry into application of the implementing act on appeals (date to be determined by the implementing act on dates)."),
        h("p", null, "For urgent matters, please contact my deputy, who is also out of the office. For very urgent matters, please consider whether the matter is really that urgent."),
        h("p", null, "Your appeal has been forwarded to the department that refused you, for impartiality."),
        h("p", { class: "mail-sig" }, "— Office of the European Ombudsman (fictional)", h("br"), "This message was not generated by AI. It was generated by procedure."),
      ),
      close,
    ),
  );
  close.addEventListener("click", () => dlg.remove());
  dlg.addEventListener("click", (e) => e.target === dlg && dlg.remove());
  return dlg;
}

/** The Notice of Non-Compliance. Returns the document node too, for PNG export. */
export function noticeView(notice: Notice, officers: Persona[]): HTMLElement {
  const issued = new Date(notice.issuedAt);
  const date = isNaN(issued.getTime()) ? notice.issuedAt : issued.toLocaleDateString("en-GB", { day: "2-digit", month: "long", year: "numeric" });
  const first = notice.findings.map((f) => safeUrl(f.provision.url)).find(Boolean) ?? null;
  const qr = first ? qrBox(first, "Scan for the law") : h("div", { class: "qr" });
  const [a, b] = notice.officers.map((id) => nameOf(officers, id)) as [Persona, Persona];

  const doc = h(
    "article",
    { class: "notice-doc" },
    h(
      "header",
      { class: "nd-head" },
      h("div", { class: "nd-emblem" }, "★"),
      h("div", null, h("b", null, "EUROPEAN COMMISSION"), h("br"), "Directorate-General for the Refusal of Startups", h("br"), "Unit R.5 — Notices, Fines and Regret"),
      h("div", { class: "nd-ref" }, "Brussels, ", date, h("br"), h("b", null, notice.serial), h("br"), "C(2026) 4812 final"),
    ),
    h("h1", null, "NOTICE OF NON-COMPLIANCE"),
    h("p", { class: "nd-sub" }, "issued pursuant to everything, in respect of"),
    h("p", { class: "nd-startup" }, notice.startup),
    h("p", null, "Having regard to the Treaty on the Functioning of the European Union, having regard to the pitch, and whereas the pitch was heard in its entirety, against advice, the Directorate-General finds as follows:"),
    h(
      "ol",
      { class: "nd-findings" },
      notice.findings.map((f) => {
        const url = safeUrl(f.provision.url);
        return h("li", null, f.text, " ", url ? h("a", { class: "chip", href: url, target: "_blank", rel: "noopener noreferrer", title: f.provision.title }, f.provision.label) : h("span", { class: "chip" }, f.provision.label));
      }),
    ),
    h("div", { class: "nd-fine" }, h("span", null, "Administrative fine"), h("strong", null, fmtEur(notice.fineEur)), h("small", null, notice.fineBasis)),
    h("p", { class: "nd-small" }, "The fine is payable within 30 days to an account that will be communicated by post, in 2031. This notice may be appealed (see Ombudsman)."),
    h(
      "footer",
      { class: "nd-sign" },
      [a, b].map((p) => h("div", { class: "sig" }, h("span", { class: "sig-ink", style: `color:${p.color}` }, p.name), h("i"), h("b", null, p.name), h("small", null, p.title))),
      qr,
    ),
    h("div", { class: "nd-stamp s1" }, "REFUSÉ"),
    h("div", { class: "nd-stamp s2" }, "PUBLIÉ AU J.O."),
    h("p", { class: "nd-foot" }, "AI-GENERATED CONTENT — Art. 50 Regulation (EU) 2024/1689. All officials are fictional; every citation is real. Not legal advice. Not even advice."),
  );

  const status = h("span", { class: "nd-status", role: "status" });
  const dl = h("button", { class: "btn primary", type: "button" }, "⬇ Download notice (PNG)");
  dl.addEventListener("click", async () => {
    dl.disabled = true;
    status.textContent = "Certifying a true copy…";
    try {
      const { toBlob } = await import("html-to-image");
      const blob = await toBlob(doc, { pixelRatio: 2, backgroundColor: "#fffef8", width: doc.offsetWidth, height: doc.offsetHeight, style: { margin: "0" } });
      if (!blob || blob.size === 0) throw new Error("empty image");
      const url = URL.createObjectURL(blob);
      const link = h("a", { href: url, download: `${notice.serial.replace(/[^\w.-]+/g, "_")}.png` });
      document.body.append(link);
      link.click();
      link.remove();
      setTimeout(() => URL.revokeObjectURL(url), 60_000);
      status.textContent = "True copy downloaded. Frame it.";
      chime();
    } catch (err) {
      console.warn("[notice] png failed", err);
      status.textContent = "The copier is broken. Please take a screenshot, in triplicate.";
    } finally {
      dl.disabled = false;
    }
  });
  const appeal = h("button", { class: "btn", type: "button", onclick: () => document.body.append(ombudsman()) }, "Appeal");
  const again = h("a", { class: "btn", href: withFlags("/") }, "Submit another startup");
  const wall = h("a", { class: "btn", href: withFlags("/wall/"), target: "_blank" }, "Official Journal — Series R ↗");

  const report = h("a", { class: "btn primary", href: REPORT_URL, target: "_blank", rel: "noopener" }, "Get the real report ↗");
  const pocket = h(
    "aside",
    { class: "pocket-card" },
    qrBox(POCKET_URL, "eurocrat.pro7ocol.com/pocket", 160),
    h(
      "div",
      null,
      h("h3", null, "Take the Directorate home"),
      h("p", null, "Your own Eurocrat, in your pocket. It refuses things on the go. Form P-1 (mobile)."),
      h("a", { class: "btn primary", href: POCKET_URL, target: "_blank", rel: "noopener" }, "Get your Pocket Eurocrat ↗"),
      h("h3", null, "Actually need to comply?"),
      h("p", null, "warden reads your idea, document or repo against the real AI Act and GDPR. No insults. Fewer, anyway."),
      report,
    ),
  );
  return h("section", { class: "verdict" }, h("div", { class: "verdict-actions" }, dl, appeal, report.cloneNode(true), wall, again, status), h("div", { class: "verdict-body" }, doc, pocket));
}
